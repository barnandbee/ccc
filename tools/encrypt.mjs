// Builds js/locks.js from a private JSON file of character cards.
//
//   node tools/encrypt.mjs path/to/cards.private.json
//
// Keep the private JSON out of the repo (anything named *.private.json is gitignored).
// Its shape is:
// {
//   "tim": { "answer": "the answer", "card": { ...anything the game should reveal on unlock... } },
//   ...
// }
import { readFileSync, writeFileSync } from 'node:fs';
import { candidates, checkHash, encrypt, tryUnlock } from '../js/lock.js';

const src = process.argv[2];
if (!src) {
  console.error('Usage: node tools/encrypt.mjs cards.private.json');
  process.exit(1);
}
const cards = JSON.parse(readFileSync(src, 'utf8'));
const out = {};
for (const [id, { answer, card }] of Object.entries(cards)) {
  const cands = candidates(answer);
  if (!cands.length) throw new Error(`${id}: answer normalises to nothing`);
  const key = cands[0];
  out[id] = { check: checkHash(id, key), data: encrypt(id, key, card) };
  if (!tryUnlock(out[id], id, answer)) throw new Error(`${id}: round trip failed`);
  console.log(`${id}: key "${key}" ok`);
}
const js = `// Generated by tools/encrypt.mjs. Do not edit by hand.\nexport const LOCKS = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync(new URL('../js/locks.js', import.meta.url), js);
console.log('Wrote js/locks.js');
