// Adds or updates characters in js/locks.js from a private JSON file.
//
//   node tools/encrypt.mjs path/to/cards.private.json
//
// Only the characters in the file are changed; everyone already in js/locks.js
// is kept, so you never need the old answers again.
// Keep the private JSON out of the repo (anything named *.private.json is gitignored).
// Its shape is:
// {
//   "tim": {
//     "answer": "Prawns",          // what's on the card
//     "key": "prawn",              // optional: the normalised word to match (see candidates() in js/lock.js)
//     "card": { ...anything the game should reveal on unlock... }
//   }
// }
import { readFileSync, writeFileSync } from 'node:fs';
import { candidates, checkHash, encrypt, tryUnlock } from '../js/lock.js';

const src = process.argv[2];
if (!src) {
  console.error('Usage: node tools/encrypt.mjs cards.private.json');
  process.exit(1);
}
const cards = JSON.parse(readFileSync(src, 'utf8'));
let existing = {};
try {
  existing = (await import('../js/locks.js')).LOCKS;
} catch { /* first run */ }
const out = { ...existing };
for (const [id, { answer, key: wanted, card, alsoAccept = [] }] of Object.entries(cards)) {
  const cands = candidates(answer);
  const key = wanted || cands[0];
  if (!key) throw new Error(`${id}: answer normalises to nothing`);
  if (!cands.includes(key)) throw new Error(`${id}: key "${key}" isn't produced by the answer "${answer}" (got ${cands.join(', ')})`);
  out[id] = { check: checkHash(id, key), data: encrypt(id, key, card) };
  for (const a of [answer, ...alsoAccept]) {
    if (!tryUnlock(out[id], id, a)) throw new Error(`${id}: "${a}" doesn't unlock`);
  }
  console.log(`${id}: key "${key}" ok`);
}
const js = `// Generated by tools/encrypt.mjs. Do not edit by hand.\nexport const LOCKS = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync(new URL('../js/locks.js', import.meta.url), js);
console.log(`Wrote js/locks.js (${Object.keys(out).length} characters)`);
